import { validateWordList } from '@crossverse/crossword-core'
import type { Difficulty } from '@crossverse/contracts'
import type { Db } from '../../src/db.ts'
import { directionsFor } from '../../src/modules/wordsearch/service.ts'

/**
 * Mots mêlés « standard » (décision D16) : grille carrée entièrement remplie, mots à trouver
 * dans tous les sens permis par le niveau, mot mystère formé par les lettres restantes.
 * Grilles produites avec `buildWordList` (crossword-core) puis figées ici : une grille jouée ne
 * change plus. Chaque mot n'y figure qu'une fois, ce que vérifie `validateWordList`.
 */
export interface SeedWordList {
  readonly slug: string
  readonly title: string
  /** Slug d'un thème ou sous-thème de `themes.ts`. */
  readonly theme: string
  readonly difficulty: Difficulty
  readonly estimatedMinutes: number
  readonly words: readonly string[]
  readonly mystery: string
  readonly mysteryClue: string
  readonly rows: readonly string[]
}

/** Problèmes d'une grille (mot absent, en double, illisible au niveau, mot mystère faux). */
export function wordListProblems(seed: SeedWordList): string[] {
  return validateWordList(seed, directionsFor(seed.difficulty)).map((p) => p.message)
}

/**
 * Ajoute les mots mêlés absents, **sans jamais écraser** une grille déjà présente (même slug),
 * comme `syncCatalog`. Idempotent, exécuté à chaque démarrage de l'API en production.
 */
export async function syncWordLists(db: Db, lists: readonly SeedWordList[]): Promise<number> {
  const themeIds = new Map(
    (await db.theme.findMany({ select: { id: true, slug: true } })).map((t) => [t.slug, t.id]),
  )
  let created = 0
  for (const seed of lists) {
    const problems = wordListProblems(seed)
    if (problems.length > 0) {
      throw new Error(`Mots mêlés « ${seed.slug} » invalides : ${problems.join(' ')}`)
    }
    const themeId = themeIds.get(seed.theme)
    if (!themeId) throw new Error(`Mots mêlés « ${seed.slug} » : thème « ${seed.theme} » inconnu.`)
    const result = await db.wordList.createMany({
      data: [
        {
          slug: seed.slug,
          title: seed.title,
          themeId,
          difficulty: seed.difficulty,
          status: 'published',
          rows: [...seed.rows],
          words: [...seed.words],
          mystery: seed.mystery,
          mysteryClue: seed.mysteryClue,
          estimatedMinutes: seed.estimatedMinutes,
        },
      ],
      skipDuplicates: true,
    })
    created += result.count
  }
  return created
}

